  function getStaticPatchFor(charId, loopIndex) {
    const idx = Number(loopIndex);
    if (!charId || !Number.isFinite(idx)) return "";
    const row = STATIC_PATCH_BY_CHAR_LOOP[charId];
    if (!row) return "";
    const v = row[idx];
    return typeof v === "string" && v.trim() ? v : "";
  }

